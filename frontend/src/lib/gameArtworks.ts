export function getGameArtwork(slug: string, image?: string): string {
  const norm = slug.toLowerCase();
  if (image && !image.endsWith(`${slug}.png`) && image !== '/images/games/default.png') {
    return image;
  }
  if (GAME_ARTWORKS[norm]) {
    return GAME_ARTWORKS[norm];
  }
  return '';
}
